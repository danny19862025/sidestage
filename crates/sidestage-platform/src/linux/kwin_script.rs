//! Small persistent KWin scripts, loaded over D-Bus and unloaded on drop.

use anyhow::{bail, Result};

pub struct KwinScript {
    conn: zbus::blocking::Connection,
    name: String,
    path: std::path::PathBuf,
}

impl KwinScript {
    /// Loads and runs `code` as KWin script `name` (replacing an older copy).
    pub fn load(name: &str, code: &str) -> Result<KwinScript> {
        let conn = zbus::blocking::Connection::session()?;
        let scripting = zbus::blocking::Proxy::new(
            &conn,
            "org.kde.KWin",
            "/Scripting",
            "org.kde.kwin.Scripting",
        )?;
        let _: bool = scripting.call("unloadScript", &(name,)).unwrap_or(false);
        let dir = std::env::var_os("XDG_RUNTIME_DIR")
            .map(std::path::PathBuf::from)
            .unwrap_or_else(std::env::temp_dir);
        let path = dir.join(format!("{name}-{}.js", std::process::id()));
        std::fs::write(&path, code)?;
        let id: i32 = scripting.call("loadScript", &(path.display().to_string(), name))?;
        if id < 0 {
            bail!("KWin refused script {name}");
        }
        let obj = format!("/Scripting/Script{id}");
        zbus::blocking::Proxy::new(&conn, "org.kde.KWin", obj.as_str(), "org.kde.kwin.Script")?
            .call::<_, _, ()>("run", &())?;
        Ok(KwinScript {
            conn,
            name: name.to_string(),
            path,
        })
    }
}

impl Drop for KwinScript {
    fn drop(&mut self) {
        if let Ok(p) = zbus::blocking::Proxy::new(
            &self.conn,
            "org.kde.KWin",
            "/Scripting",
            "org.kde.kwin.Scripting",
        ) {
            let _: zbus::Result<bool> = p.call("unloadScript", &(self.name.as_str(),));
        }
        let _ = std::fs::remove_file(&self.path);
    }
}

/// Keeps Sidestage's sidebar on every virtual desktop. KWin ignores both
/// the X11 `_NET_WM_DESKTOP` request and the window-management protocol's
/// "on all desktops" state for this dock, but honours it from a script.
pub fn sticky_sidebar() -> Result<KwinScript> {
    let pid = std::process::id();
    KwinScript::load(
        "sidestage-sticky",
        &format!(
            r#"// Generated by Sidestage: keep the sidebar on all virtual desktops.
function fix(w) {{
    if (w && w.pid === {pid} && w.resourceClass === "sidestage" && w.caption === "Sidestage" && !w.onAllDesktops)
        w.onAllDesktops = true;
}}
workspace.windowList().forEach(fix);
workspace.windowAdded.connect(fix);
"#
        ),
    )
}
